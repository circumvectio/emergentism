class RegisterError(RuntimeError):
    """The requested register snapshot is ambiguous or unsafe."""


@dataclass(frozen=True)
class IndexEntry:
    mode: str
    oid: str
    path: str


def _git(repo_root, *args, input_bytes=None):
    return subprocess.run(
        ["git", "-C", repo_root, *args],
        input=input_bytes,
        check=True,
        capture_output=True,
    ).stdout


def parse_index_records(raw):
    """Parse ``git ls-files -s -z`` and reject conflicts or duplicate paths."""
    entries = []
    seen = set()
    for record in raw.split(b"\0"):
        if not record:
            continue
        meta, separator, encoded_path = record.partition(b"\t")
        fields = meta.split()
        if not separator or len(fields) != 3:
            raise RegisterError("malformed git ls-files -s -z record")
        mode = fields[0].decode("ascii", "strict")
        oid = fields[1].decode("ascii", "strict")
        stage = fields[2].decode("ascii", "strict")
        path = encoded_path.decode("utf-8", "surrogateescape")
        if stage != "0":
            raise RegisterError(f"unmerged index entry at stage {stage}: {path}")
        if path in seen:
            raise RegisterError(f"duplicate path in Git index: {path}")
        seen.add(path)
        entries.append(IndexEntry(mode=mode, oid=oid, path=path))
    return sorted(entries, key=lambda entry: entry.path)


def git_index_entries(repo_root=REPO_ROOT):
    return parse_index_records(_git(repo_root, "ls-files", "-s", "-z"))


def parse_cat_file_batch(raw, requested_oids):
    """Parse ``git cat-file --batch`` output for an ordered list of object IDs."""
    cursor = 0
    by_oid = {}
    for requested in requested_oids:
        line_end = raw.find(b"\n", cursor)
        if line_end < 0:
            raise RegisterError(f"truncated git cat-file header for {requested}")
        header = raw[cursor:line_end].decode("ascii", "strict").split()
        cursor = line_end + 1
        if len(header) == 2 and header[1] == "missing":
            raise RegisterError(f"missing indexed object: {requested}")
        if len(header) != 3:
            raise RegisterError(f"malformed git cat-file header for {requested}")
        returned_oid, object_type, size_text = header
        if returned_oid != requested:
            raise RegisterError(
                f"git cat-file returned {returned_oid} while {requested} was requested"
            )
        if object_type != "blob":
            raise RegisterError(
                f"indexed path resolves to {object_type}, not blob: {requested}"
            )
        try:
            size = int(size_text)
        except ValueError as exc:
            raise RegisterError(f"invalid blob size for {requested}") from exc
        end = cursor + size
        if end > len(raw) or raw[end:end + 1] != b"\n":
            raise RegisterError(f"truncated git cat-file payload for {requested}")
        by_oid[requested] = raw[cursor:end]
        cursor = end + 1
    if cursor != len(raw):
        raise RegisterError("unexpected trailing bytes from git cat-file --batch")
    return by_oid


def git_index_blobs(entries, repo_root=REPO_ROOT):
    """Return ``path -> exact index blob bytes`` using one batched Git read."""
    requested_oids = list(dict.fromkeys(entry.oid for entry in entries))
    if not requested_oids:
        return {}
    request = b"".join(oid.encode("ascii") + b"\n" for oid in requested_oids)
    raw = _git(repo_root, "cat-file", "--batch", input_bytes=request)
    by_oid = parse_cat_file_batch(raw, requested_oids)
    return {entry.path: by_oid[entry.oid] for entry in entries}


def index_snapshot(repo_root=REPO_ROOT):
    entries = git_index_entries(repo_root)
    blobs = git_index_blobs(entries, repo_root)
    if len(blobs) != len(entries):
        raise RegisterError("Git-index snapshot lost or duplicated a tracked path")
    return entries, blobs


def sha256_bytes(raw):
    return hashlib.sha256(raw).hexdigest()


def read_frontmatter(raw):
    """Cheap first-block YAML scan from immutable index bytes."""
    text = raw[:FM_READ_BYTES].decode("utf-8", "replace")
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        return {}
    block = []
    for line in lines[1:]:
        if line.strip() == "---":
            break
        block.append(line)
    else:
        return {}
    fields = {}
    for line in block:
        match = re.match(r"^([A-Za-z_][\w-]*):\s*(.*)$", line)
        if match:
            value = match.group(2).strip().strip('"').strip("'")
            fields.setdefault(match.group(1), value)
    return fields


def authority_from_status(status):
    if not status:
        return "unrated"
    upper = status.upper()
    if any(token in upper for token in ("STAGED", "PENDING", "[D]", "DRAFT")):
        return "staged"
    if "SIGNED" in upper:
        return "signed"
    return "unrated"


def evidence_tier_from(fields):
    value = fields.get("evidence_tier")
    if not value:
        return None
    match = TIER_RE.search(value)
    return match.group(0) if match else None


def artifact_class(path):
    top = path.split("/", 1)[0]
    if top in ("90_ARCHIVE", "91_COMPATIBILITY"):
        return "archive"
    if top == "12_PUBLIC_SITE":
        return "site"
    if top == "09_TOOLS":
        return "tool"
    base = path.rsplit("/", 1)[-1]
    low = base.lower()
    stem, extension = os.path.splitext(low)
    if "receipt" in low or "50_audits_and_executions" in path.lower():
        return "receipt"
    if low in CONFIG_NAMES or stem in CONFIG_NAMES or extension in CONFIG_EXTS:
        return "config"
    if extension in (".md", ".markdown"):
        return "doctrine"
    return "other"


def k_relation(path):
    if path in K_EXACT:
        return K_EXACT[path]
    for prefix, relation in K_PREFIX:
        if path.startswith(prefix):
            return relation
    return None


def map_disposition(raw):
    upper = (raw or "").upper()
    if not upper:
        return "keep"
    if any(token in upper for token in ("ARCHIVE", "TOMBSTONE", "STONE")):
        return "tombstone-candidate"
    if any(token in upper for token in ("ABSORB", "REVISE", "STAGED", "ROUTE", "SUCCESSION")):
        return "staged"
    return "keep"


def load_manifest_dispositions(raw, key_col):
    table = {}
    if not raw:
        return table
    text = raw.decode("utf-8", "replace")
    for row in csv.DictReader(io.StringIO(text)):
        key = (row.get(key_col) or "").strip()
        if key:
            table[key] = map_disposition(row.get("disposition"))
    return table


def build_ref_index(tracked, blobs):
    """Return basename hit counts from tracked Markdown/HTML index blobs."""
    basenames = {path.rsplit("/", 1)[-1] for path in tracked}
    counts = Counter()
    for path in tracked:
        if not path.lower().endswith(CORPUS_EXTS):
            continue
        text = blobs[path].decode("utf-8", "replace")
        for token, count in Counter(TOKEN_RE.findall(text)).items():
            if token in basenames:
                counts[token] += count
    return counts


