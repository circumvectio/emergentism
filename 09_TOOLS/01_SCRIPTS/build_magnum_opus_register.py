def file_entry(path, raw, ref_counts, manifest_disp):
    fields = read_frontmatter(raw) if path.lower().endswith((".md", ".markdown")) else {}
    base = path.rsplit("/", 1)[-1]
    top = path.split("/", 1)[0]
    return {
        "path": path,
        "sha256": sha256_bytes(raw),
        "bytes": len(raw),
        "owner_lane": top if "/" in path else "root",
        "artifact_class": artifact_class(path),
        "authority_status": authority_from_status(fields.get("status")),
        "evidence_tier": evidence_tier_from(fields),
        "k_relation": k_relation(path),
        "public_projection": path if path.startswith("12_PUBLIC_SITE/") else None,
        "disposition": manifest_disp.get(path, "keep"),
        "destination": None,
        "absorber": None,
        "inbound_references": min(ref_counts.get(base, 0), REF_CAP),
        "gate": None,
        "review_state": "unreviewed",
    }


def folder_type(path):
    if path == ".":
        return "other"
    top = path.split("/", 1)[0]
    if top in ("00_META", "00_CONTROL"):
        return "meta"
    if top in ("90_ARCHIVE", "91_COMPATIBILITY"):
        return "archive"
    if top == "12_PUBLIC_SITE":
        return "site"
    if top == "09_TOOLS":
        return "tool"
    if top == "10_SEED":
        return "seed"
    if re.match(r"^(0[1-8]|11)_", top):
        return "lane"
    return "other"


def folder_scope_guess(raw):
    """Derive one scope line from front-door index bytes."""
    if raw is None:
        return None
    fields = read_frontmatter(raw)
    for key in ("canonical_phrase", "title", "description"):
        value = fields.get(key)
        if value:
            return value[:140]
    in_frontmatter = False
    for line in raw[:FM_READ_BYTES].decode("utf-8", "replace").splitlines():
        stripped = line.strip()
        if stripped == "---":
            in_frontmatter = not in_frontmatter
            continue
        if in_frontmatter or not stripped or stripped.startswith("#") or stripped.startswith("<!--"):
            continue
        return stripped[:140]
    return None


def build_folder_entries(tracked, blobs, manifest_disp):
    parents = {}
    for path in tracked:
        directory = path.rsplit("/", 1)[0] if "/" in path else "."
        parts = directory.split("/") if directory != "." else ["."]
        for index in range(len(parts)):
            parents.setdefault("/".join(parts[:index + 1]), 0)
        parents[directory] += 1
    file_set = set(tracked)
    entries = []
    for folder in sorted(parents):
        prefix = "" if folder == "." else folder + "/"
        door = next(
            (prefix + name for name in ("README.md", "AGENTS.md", "index.html")
             if prefix + name in file_set),
            None,
        )
        door_raw = blobs.get(door) if door else None
        door_fields = read_frontmatter(door_raw) if door and door.lower().endswith(".md") else {}
        count = sum(1 for path in tracked if path.startswith(prefix)) if prefix else len(tracked)
        entries.append({
            "path": folder,
            "type": folder_type(folder),
            "nearest_front_door": door,
            "front_door_requirement": "present" if door else "missing",
            "owns": folder_scope_guess(door_raw),
            "must_not_own": None,
            "status": authority_from_status(door_fields.get("status")),
            "tracked_file_count": count,
            "disposition": manifest_disp.get(folder, "keep"),
            "gate": None,
            "review_state": "unreviewed",
        })
    return entries


def validate_register(doc, label):
    entries = doc.get("entries")
    if not isinstance(entries, list):
        raise RegisterError(f"{label}: entries must be a list")
    if doc.get("entry_count") != len(entries):
        raise RegisterError(
            f"{label}: entry_count {doc.get('entry_count')!r} != {len(entries)}"
        )
    paths = [entry.get("path") for entry in entries]
    if any(not isinstance(path, str) for path in paths):
        raise RegisterError(f"{label}: every entry requires a string path")
    if len(paths) != len(set(paths)):
        raise RegisterError(f"{label}: duplicate entry paths")
    if paths != sorted(paths):
        raise RegisterError(f"{label}: entries are not sorted by path")


def derive(repo_root=REPO_ROOT, snapshot=None):
    if snapshot is None:
        index_entries, blobs = index_snapshot(repo_root)
    else:
        index_entries, blobs = snapshot
    tracked = [entry.path for entry in index_entries]
    if len(tracked) != len(set(tracked)) or set(tracked) != set(blobs):
        raise RegisterError("invalid Git-index snapshot: paths are not one-to-one")
    if SELF_PATH not in blobs:
        raise RegisterError(f"tracked self register is required: {SELF_PATH}")

    file_disp = load_manifest_dispositions(blobs.get(FILE_MANIFEST_REL, b""), "path")
    folder_disp = load_manifest_dispositions(blobs.get(FOLDER_MANIFEST_REL, b""), "folder")
    ref_counts = build_ref_index(tracked, blobs)
    file_entries = [
        self_entry() if path == SELF_PATH
        else file_entry(path, blobs[path], ref_counts, file_disp)
        for path in tracked
    ]
    file_entries.sort(key=lambda entry: entry["path"])
    folder_entries = build_folder_entries(tracked, blobs, folder_disp)
    file_doc = {
        "schema": "magnum-opus/file-register/v1",
        "generator": "09_TOOLS/01_SCRIPTS/build_magnum_opus_register.py",
        "source": "Git index paths and blob bytes (deterministic; no timestamps)",
        "entry_count": len(file_entries),
        "entries": file_entries,
    }
    folder_doc = {
        "schema": "magnum-opus/folder-register/v1",
        "generator": "09_TOOLS/01_SCRIPTS/build_magnum_opus_register.py",
        "source": "Git index directory closure and blob bytes (deterministic; no timestamps)",
        "entry_count": len(folder_entries),
        "entries": folder_entries,
    }
    validate_register(file_doc, FILE_REG_REL)
    validate_register(folder_doc, FOLDER_REG_REL)
    return file_doc, folder_doc


def _decode_z_paths(raw):
    return [
        item.decode("utf-8", "surrogateescape")
        for item in raw.split(b"\0")
        if item
    ]


def is_register_output(path):
    return path in GENERATED_REGISTER_PATHS


def assert_write_safe(repo_root=REPO_ROOT):
    """Require every non-generated change to be represented in the Git index."""
    unstaged = _decode_z_paths(_git(repo_root, "diff", "--name-only", "-z"))
    untracked = _decode_z_paths(
        _git(repo_root, "ls-files", "--others", "--exclude-standard", "-z")
    )
    unsafe = sorted({path for path in unstaged + untracked if not is_register_output(path)})
    if unsafe:
        preview = "\n  ".join(unsafe[:25])
        suffix = "\n  ..." if len(unsafe) > 25 else ""
        raise RegisterError(
            "--write requires all non-register changes staged; unresolved paths:\n  "
            + preview + suffix
        )


def serialized(doc):
    return (json.dumps(doc, ensure_ascii=False, indent=2) + "\n").encode("utf-8")


def dump(doc, abs_path):
    with open(abs_path, "wb") as handle:
        handle.write(serialized(doc))


def write_registers(file_doc, folder_doc, repo_root=REPO_ROOT):
    """Write only the two undated live registers."""
    validate_register(file_doc, FILE_REG_REL)
    validate_register(folder_doc, FOLDER_REG_REL)
    register_dir = os.path.join(repo_root, REG_DIR_REL)
    os.makedirs(register_dir, exist_ok=True)
    dump(file_doc, os.path.join(repo_root, FILE_REG_REL))
    dump(folder_doc, os.path.join(repo_root, FOLDER_REG_REL))


def diff_docs(derived, on_disk):
    validate_register(derived, "derived register")
    validate_register(on_disk, "on-disk register")
    derived_entries = {entry["path"]: entry for entry in derived["entries"]}
    disk_entries = {entry["path"]: entry for entry in on_disk["entries"]}
    added = sorted(set(derived_entries) - set(disk_entries))
    removed = sorted(set(disk_entries) - set(derived_entries))
    changed = []
    metadata_keys = sorted((set(derived) | set(on_disk)) - {"entries"})
    metadata_changes = [
        key for key in metadata_keys if derived.get(key) != on_disk.get(key)
    ]
    if metadata_changes:
        changed.append(("<register metadata>", metadata_changes[:4]))
    for path in sorted(set(derived_entries) & set(disk_entries)):
        if derived_entries[path] != disk_entries[path]:
            fields = [
                key for key in derived_entries[path]
                if derived_entries[path].get(key) != disk_entries[path].get(key)
            ]
            changed.append((path, fields[:4]))
    return added, removed, changed


def main(argv=None):
    parser = argparse.ArgumentParser(description="Build/check deterministic Git-index registers.")
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="generate FILE_REGISTER.json + FOLDER_REGISTER.json")
    mode.add_argument("--check", action="store_true", help="report drift against the Git-index snapshot")
    args = parser.parse_args(argv)

    try:
        if args.write:
            assert_write_safe(REPO_ROOT)
        file_doc, folder_doc = derive(REPO_ROOT)

        if args.write:
            write_registers(file_doc, folder_doc, REPO_ROOT)
            print(f"wrote {FILE_REG_REL} ({file_doc['entry_count']} entries)")
            print(f"wrote {FOLDER_REG_REL} ({folder_doc['entry_count']} entries)")
            return 0

        drift = False
        for relative, derived_doc in (
            (FILE_REG_REL, file_doc),
            (FOLDER_REG_REL, folder_doc),
        ):
            absolute = os.path.join(REPO_ROOT, relative)
            try:
                with open(absolute, encoding="utf-8") as handle:
                    on_disk = json.load(handle)
                added, removed, changed = diff_docs(derived_doc, on_disk)
            except (OSError, json.JSONDecodeError, RegisterError) as exc:
                print(f"DRIFT {relative}: invalid or unreadable on disk ({exc})")
                drift = True
                continue
            if added or removed or changed:
                drift = True
                print(
                    f"DRIFT {relative}: +{len(added)} added, "
                    f"-{len(removed)} removed, ~{len(changed)} changed"
                )
                for path in added[:25]:
                    print(f"  added   {path}")
                for path in removed[:25]:
                    print(f"  removed {path}")
                for path, fields in changed[:25]:
                    print(f"  changed {path} ({', '.join(fields)})")
            else:
                print(f"clean {relative} ({derived_doc['entry_count']} entries)")
        return 1 if drift else 0
    except (RegisterError, subprocess.CalledProcessError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
